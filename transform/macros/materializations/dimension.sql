{#
  materialized='dimension' - keystore backed dimension, SCD2 by default.

  The model selects change records of the members:
      <business_key>, [<effective_from>], attribute columns...
  config:
      business_key    (required) column holding the business key
      scd_type        2 (default, var scd_default_type) or 1
      effective_from  (required for SCD2; optional for SCD1 = "latest wins") change timestamp
      surrogate_key   name of the key column (default: <model name without dim_>_key)

  Output columns:
      <surrogate_key>, <business_key>, attributes..., is_inferred, is_erased
      and for SCD2: valid_from, valid_to, is_current   (valid_from inclusive, valid_to exclusive)

  The table is rebuilt from its source on every run; surrogate keys come from the keystore, so a
  rebuild (or dropping the table) never changes a key. Consecutive records with unchanged
  attributes collapse into one version.
#}
{% materialization dimension, adapter='trino' %}
  {%- set business_key = config.require('business_key') -%}
  {%- set scd_type = config.get('scd_type', var('scd_default_type')) | int -%}
  {%- set effective_from = config.get('effective_from') -%}
  {%- set surrogate_key = config.get('surrogate_key', this.identifier | replace('dim_', '') ~ '_key') -%}
  {%- if scd_type not in [1, 2] -%}
    {{ exceptions.raise_compiler_error("scd_type must be 1 or 2, got " ~ scd_type) }}
  {%- endif -%}
  {%- if scd_type == 2 and not effective_from -%}
    {{ exceptions.raise_compiler_error("SCD2 dimension " ~ this ~ " needs config effective_from") }}
  {%- endif -%}

  {%- set target_relation = this.incorporate(type='table') -%}
  {%- set existing_relation = load_cached_relation(this) -%}
  {%- set stage_relation = make_intermediate_relation(target_relation, '__stage') -%}
  {%- set grant_config = config.get('grants') -%}
  {%- set bot = var('scd_begin_of_time') -%}
  {%- set eot = var('scd_end_of_time') -%}

  {{ run_hooks(pre_hooks) }}

  {# 1. stage the model query #}
  {% call statement('stage') %}
    {{ create_table_as(False, stage_relation, sql, 'replace') }}
  {% endcall %}
  {%- set stage_columns = adapter.get_columns_in_relation(stage_relation) -%}
  {%- set reserved = [business_key | lower] + ([effective_from | lower] if effective_from else []) -%}
  {%- set attributes = [] -%}
  {%- for col in stage_columns if col.name | lower not in reserved -%}
    {%- do attributes.append(col) -%}
  {%- endfor -%}
  {%- for col in stage_columns if col.name | lower in [surrogate_key, 'valid_from', 'valid_to', 'is_current', 'is_inferred', 'is_erased'] and col.name | lower not in reserved -%}
    {{ exceptions.raise_compiler_error("column " ~ col.name ~ " is generated by the dimension materialization") }}
  {%- endfor -%}

  {# 2. versions: collapse unchanged records; one row per business key (SCD1) or per version (SCD2) #}
  {%- set versions_sql -%}
    with src as (
      select
        cast({{ business_key }} as varchar) as _bk,
        {% if effective_from %}{{ ts6(effective_from) }}{% else %}{{ bot }}{% endif %} as _eff,
        to_hex(sha256(to_utf8(concat(''
          {%- for col in attributes %}, coalesce(cast({{ adapter.quote(col.name) }} as varchar), chr(0)), chr(31){% endfor %})))) as _row_hash,
        s.*
      from {{ stage_relation }} s
      where {{ business_key }} is not null
    ),
    marked as (
      select *, lag(_row_hash) over (partition by _bk order by _eff) as _prev_hash,
             row_number() over (partition by _bk order by _eff desc) as _recency
      from src
    ),
    {% if scd_type == 2 %}
    versions as (
      select *,
        row_number() over (partition by _bk order by _eff) as _version_no,
        lead(_eff) over (partition by _bk order by _eff) as _next_eff,
        cast(_eff at time zone 'UTC' as varchar) as _version_key
      from marked
      where _prev_hash is null or _prev_hash <> _row_hash
    )
    {% else %}
    versions as (
      select *, 1 as _version_no, cast(null as timestamp(6) with time zone) as _next_eff, '' as _version_key
      from marked
      where _recency = 1
    )
    {% endif %}
  {%- endset -%}

  {# 3. the input must identify a record unambiguously #}
  {% set duplicates_query %}
    select count(*) from (
      select 1 from {{ stage_relation }} where {{ business_key }} is not null
      group by {{ business_key }}{% if effective_from %}, {{ effective_from }}{% endif %} having count(*) > 1
    )
  {% endset %}
  {% if run_query(duplicates_query).columns[0].values()[0] | int > 0 %}
    {{ exceptions.raise_compiler_error("dimension " ~ this ~ ": input has several rows per (" ~ business_key ~ (", " ~ effective_from if effective_from else "") ~ ")") }}
  {% endif %}

  {# 4. keys: reuse existing, allocate missing #}
  {% set candidates_sql %}
    {{ versions_sql }} select _bk as business_key, _version_key as version_key from versions
  {% endset %}
  {% set ks = keystore_allocate(this.identifier, candidates_sql, member_type='regular') %}

  {# 5. (re)build the dimension #}
  {% call statement('main') %}
    create or replace table {{ target_relation }}
    {%- if model.description and config.persist_relation_docs() %} comment {{ "'" ~ model.description | replace("'", "''") ~ "'" }}{% endif %}
    as
    {{ versions_sql }}
    select
      k.surrogate_key as {{ surrogate_key }},
      v.{{ adapter.quote(business_key) }},
      {%- for col in attributes %}
      v.{{ adapter.quote(col.name) }},
      {%- endfor %}
      {%- if scd_type == 2 %}
      case when v._version_no = 1 then {{ bot }} else v._eff end as valid_from,
      coalesce(v._next_eff, {{ eot }}) as valid_to,
      v._next_eff is null as is_current,
      {%- endif %}
      false as is_inferred,
      false as is_erased
    from versions v
    join {{ ks }} k on k.business_key = v._bk and k.version_key = v._version_key
    union all
    -- unknown member, inferred members without master data yet, erased members (anonymous)
    select
      k.surrogate_key,
      cast(k.business_key as {{ (stage_columns | selectattr('name', 'equalto', business_key) | first).data_type }}),
      {%- for col in attributes %}
      cast(null as {{ col.data_type }}),
      {%- endfor %}
      {%- if scd_type == 2 %}
      {{ bot }}, {{ eot }}, true,
      {%- endif %}
      k.member_type = 'inferred',
      k.member_type = 'erased'
    from {{ ks }} k
    where k.member_type in ('unknown', 'inferred', 'erased')
  {% endcall %}

  {% call statement('drop_stage') %}
    drop table if exists {{ stage_relation }}
  {% endcall %}

  {% do persist_docs(target_relation, model, for_relation=false) %}
  {% set should_revoke = should_revoke(existing_relation, full_refresh_mode=True) %}
  {% do apply_grants(target_relation, grant_config, should_revoke=should_revoke) %}
  {{ run_hooks(post_hooks) }}
  {{ return({'relations': [target_relation]}) }}
{% endmaterialization %}
