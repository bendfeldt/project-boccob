#!/usr/bin/env bash
# Local integration harness: RustFS + Polaris + Trino (+ OPA) as throwaway podman containers.
# All containers/networks are prefixed "sol-" and removed by `harness.sh down`.
# Credentials are generated per harness instance and written to .harness/env (git-ignored).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
STATE_DIR="${HARNESS_STATE_DIR:-$ROOT/.harness}"
NET=sol-test

# image pins (tag@digest); override through the environment for mirrors
RUSTFS_IMAGE="${RUSTFS_IMAGE:-docker.io/rustfs/rustfs:v1.0.0-rc.5}"
POLARIS_IMAGE="${POLARIS_IMAGE:-docker.io/apache/polaris:1.9.0}"
TRINO_IMAGE="${TRINO_IMAGE:-docker.io/trinodb/trino:484}"
OPA_IMAGE="${OPA_IMAGE:-docker.io/openpolicyagent/opa:1.22.4-static}"

RUSTFS_PORT="${RUSTFS_PORT:-19000}"
POLARIS_PORT="${POLARIS_PORT:-18181}"
POLARIS_MGMT_PORT="${POLARIS_MGMT_PORT:-18182}"
TRINO_PORT="${TRINO_PORT:-18080}"
OPA_PORT="${OPA_PORT:-18281}"
WITH_OPA="${WITH_OPA:-1}"
LAYERS=(raw clean consolidated curated)

log() { printf '[harness] %s\n' "$*" >&2; }

wait_http() { # url [tries]
  local url="$1" tries="${2:-90}"
  for _ in $(seq "$tries"); do
    if curl -fsS --noproxy '*' -o /dev/null "$url" 2>/dev/null; then return 0; fi
    sleep 2
  done
  log "timeout waiting for $url"; return 1
}

gen_env() {
  mkdir -p "$STATE_DIR"
  if [[ ! -f "$STATE_DIR/env" ]]; then
    umask 077
    local s3_secret polaris_secret pepper
    s3_secret="$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 32)"
    polaris_secret="$(head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 32)"
    pepper="$(head -c 32 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 40)"
    cat > "$STATE_DIR/env" <<ENV
# generated by tests/integration/harness.sh - throwaway credentials, never commit
export S3_ENDPOINT_URL=http://localhost:${RUSTFS_PORT}
export S3_ACCESS_KEY_ID=solharness
export S3_SECRET_ACCESS_KEY=${s3_secret}
export S3_REGION=eu-north-1
export RAW_BUCKET=lakehouse-raw
export POLARIS_URI=http://localhost:${POLARIS_PORT}/api/catalog
export POLARIS_CLIENT_ID=root
export POLARIS_CLIENT_SECRET=${polaris_secret}
export POLARIS_SCOPE=PRINCIPAL_ROLE:ALL
export TRINO_HOST=localhost
export TRINO_PORT=${TRINO_PORT}
export TRINO_USER=svc-dagster
export TRINO_HTTP_SCHEME=http
export PSEUDONYM_PEPPER=${pepper}
export OPA_URL=http://localhost:${OPA_PORT}
ENV
  fi
  # shellcheck disable=SC1091
  source "$STATE_DIR/env"
}

up() {
  gen_env
  podman network exists "$NET" || podman network create "$NET" >/dev/null

  log "starting RustFS"
  podman run -d --replace --name sol-rustfs --network "$NET" --memory 2g \
    -p "127.0.0.1:${RUSTFS_PORT}:9000" \
    -e RUSTFS_ACCESS_KEY="$S3_ACCESS_KEY_ID" -e RUSTFS_SECRET_KEY="$S3_SECRET_ACCESS_KEY" \
    -e RUSTFS_ADDRESS=":9000" -e RUSTFS_CONSOLE_ENABLE=false \
    "$RUSTFS_IMAGE" >/dev/null
  wait_http "http://localhost:${RUSTFS_PORT}/health" || wait_http "http://localhost:${RUSTFS_PORT}/minio/health/live" 5

  log "creating versioned buckets"
  (cd "$ROOT" && uv run --no-sync python - <<'PY'
import os, s3fs
fs = s3fs.S3FileSystem(key=os.environ["S3_ACCESS_KEY_ID"], secret=os.environ["S3_SECRET_ACCESS_KEY"],
                       client_kwargs={"endpoint_url": os.environ["S3_ENDPOINT_URL"], "region_name": os.environ["S3_REGION"]})
from lakehouse.objectstore import _sync_call, enable_versioning
for layer in ("raw", "clean", "consolidated", "curated"):
    b = f"lakehouse-{layer}"
    if not fs.exists(b):
        fs.mkdir(b)
    enable_versioning(fs, b)  # as on the platform: deletes leave noncurrent versions behind
    assert _sync_call(fs, "get_bucket_versioning", Bucket=b).get("Status") == "Enabled", b
print("buckets (versioned):", sorted(fs.ls("")))
PY
  )

  log "starting Polaris"
  podman run -d --replace --name sol-polaris --network "$NET" --memory 1g \
    -p "127.0.0.1:${POLARIS_PORT}:8181" -p "127.0.0.1:${POLARIS_MGMT_PORT}:8182" \
    -e POLARIS_BOOTSTRAP_CREDENTIALS="POLARIS,${POLARIS_CLIENT_ID},${POLARIS_CLIENT_SECRET}" \
    -e AWS_ACCESS_KEY_ID="$S3_ACCESS_KEY_ID" -e AWS_SECRET_ACCESS_KEY="$S3_SECRET_ACCESS_KEY" \
    -e AWS_REGION="$S3_REGION" \
    -e JAVA_MAX_MEM_RATIO=60 \
    "$POLARIS_IMAGE" >/dev/null
  wait_http "http://localhost:${POLARIS_MGMT_PORT}/q/health"

  log "creating Polaris catalogs"
  local token
  token="$(curl -fsS --noproxy '*' "http://localhost:${POLARIS_PORT}/api/catalog/v1/oauth/tokens" \
    -d grant_type=client_credentials -d "client_id=${POLARIS_CLIENT_ID}" \
    -d "client_secret=${POLARIS_CLIENT_SECRET}" -d scope=PRINCIPAL_ROLE:ALL \
    | python3 -c 'import sys,json; print(json.load(sys.stdin)["access_token"])')"
  for layer in "${LAYERS[@]}"; do
    curl -fsS --noproxy '*' -X POST "http://localhost:${POLARIS_PORT}/api/management/v1/catalogs" \
      -H "Authorization: Bearer ${token}" -H 'Content-Type: application/json' -d @- >/dev/null <<JSON
{"catalog": {"name": "${layer}", "type": "INTERNAL",
  "properties": {"default-base-location": "s3://lakehouse-${layer}/iceberg", "polaris.config.drop-with-purge.enabled": "true"},
  "storageConfigInfo": {"storageType": "S3", "allowedLocations": ["s3://lakehouse-${layer}/"],
    "endpoint": "http://localhost:${RUSTFS_PORT}", "endpointInternal": "http://sol-rustfs:9000",
    "pathStyleAccess": true, "stsUnavailable": true, "region": "${S3_REGION}"}}}
JSON
    curl -fsS --noproxy '*' -X PUT \
      "http://localhost:${POLARIS_PORT}/api/management/v1/catalogs/${layer}/catalog-roles/catalog_admin/grants" \
      -H "Authorization: Bearer ${token}" -H 'Content-Type: application/json' \
      -d '{"grant": {"type": "catalog", "privilege": "CATALOG_MANAGE_CONTENT"}}' >/dev/null
  done

  if [[ "$WITH_OPA" == "1" ]]; then
    log "building OPA bundle and starting OPA"
    "$ROOT/scripts/build-opa-bundle.sh" >/dev/null
    podman run -d --replace --name sol-opa --network "$NET" --memory 256m \
      -p "127.0.0.1:${OPA_PORT}:8181" \
      -v "$ROOT/dist/opa:/bundles:ro,Z" \
      "$OPA_IMAGE" run --server --addr :8181 --log-level error -b /bundles/bundle.tar.gz >/dev/null
    wait_http "http://localhost:${OPA_PORT}/health"
  fi

  log "starting Trino"
  local etc="$STATE_DIR/trino-etc"
  rm -rf -- "${etc:?}"; mkdir -p "$etc/catalog"
  cp "$HERE/trino/config.properties" "$HERE/trino/jvm.config" "$HERE/trino/node.properties" \
     "$HERE/trino/log.properties" "$HERE/trino/group-provider.properties" "$HERE/trino/groups.txt" "$etc/"
  if [[ "$WITH_OPA" == "1" ]]; then cp "$HERE/trino/access-control.properties" "$etc/"; fi
  for layer in "${LAYERS[@]}"; do
    sed "s/@LAYER@/${layer}/g" "$HERE/trino/catalog.properties.tpl" > "$etc/catalog/${layer}.properties"
  done
  chmod -R a+rX "$etc"
  podman run -d --replace --name sol-trino --network "$NET" --memory 3g \
    -p "127.0.0.1:${TRINO_PORT}:8080" \
    -v "$etc:/etc/trino:ro,Z" \
    -e S3_ACCESS_KEY_ID="$S3_ACCESS_KEY_ID" -e S3_SECRET_ACCESS_KEY="$S3_SECRET_ACCESS_KEY" \
    -e S3_REGION="$S3_REGION" \
    -e POLARIS_CREDENTIAL="${POLARIS_CLIENT_ID}:${POLARIS_CLIENT_SECRET}" \
    "$TRINO_IMAGE" >/dev/null
  for _ in $(seq 90); do
    if curl -fsS --noproxy '*' "http://localhost:${TRINO_PORT}/v1/info" 2>/dev/null | grep -q '"starting":false'; then
      log "harness is up (env: $STATE_DIR/env)"; return 0
    fi
    sleep 2
  done
  log "Trino did not start"; podman logs --tail 40 sol-trino >&2; return 1
}

down() {
  podman rm -f -t 2 sol-trino sol-opa sol-polaris sol-rustfs >/dev/null 2>&1 || true
  podman network rm -f "$NET" >/dev/null 2>&1 || true
  rm -rf -- "${STATE_DIR:?}"
  log "harness removed"
}

status() { podman ps -a --filter name=sol- --format '{{.Names}}\t{{.Status}}\t{{.Image}}'; }

case "${1:-}" in
  up) up ;;
  down) down ;;
  status) status ;;
  *) echo "usage: $0 up|down|status" >&2; exit 2 ;;
esac
